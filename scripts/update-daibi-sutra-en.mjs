<p style="text-align: justify;">Then Avalokiteśvara Bodhisattva arose from his seat, bared his right shoulder, joined his palms toward the Buddha, and said: "World-Honored One! I have a mantra of the Great Compassionate Heart and now wish to proclaim it. It is for the purpose of enabling all living beings to obtain peace and joy, to eradicate all illnesses, to prolong life, to gain abundance, to extinguish all heavy sins and offenses, to depart from hindrances and fears, and to swiftly fulfill all pure aspirations."</p>

