export function practiceUi(isEn: boolean, source: string): string {
  return isEn ? (english[source] ?? source) : source;
}

export function practiceLogUnit(isEn: boolean, type: string): string {
  const unit = type === 'Thọ giới' ? 'lần'
    : type === 'Ngồi thiền' || type === 'Nghe pháp thoại' ? 'phút'
    : type === 'Lễ Phật' ? 'lạy'
    : type === 'Chép kinh' ? 'lượt'
    : type === 'Chép danh hiệu' ? 'câu'
    : 'biến';
  return practiceUi(isEn, unit);
}

