/** Counted labels; standalone headings retain their existing translations. */
export function practiceCountUnit(isEn: boolean, unit: string, count: number): string {
  if (!isEn) return unit;
  const forms: Record<string, readonly [string, string]> = {
    'ngày': ['day', 'days'], 'phút': ['min', 'mins'], 'giờ': ['hour', 'hours'],
    'lạy': ['prostration', 'prostrations'], 'lượt': ['session', 'sessions'],
    'câu': ['phrase', 'phrases'], 'biến': ['count', 'counts'],
  };
  return forms[unit]?.[count === 1 ? 0 : 1] ?? practiceUi(isEn, unit);
}
